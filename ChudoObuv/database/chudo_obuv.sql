-- =====================================================================
-- База данных "Чудо Обувь" (PostgreSQL). Модуль 1.
-- Запуск:  createdb chudo_obuv
--          psql -U postgres -d chudo_obuv -f chudo_obuv.sql
-- Скрипт идемпотентный: пересоздаёт таблицы и заново загружает данные.
-- Схема в 3НФ: роли, категории, подкатегории и производители вынесены в
-- справочники; состав заказа хранит цену на момент оформления.
-- =====================================================================
SET client_encoding = 'UTF8';

DROP TABLE IF EXISTS order_items, orders, stock_items, products, sizes,
                     manufacturers, subcategories, categories, users, roles CASCADE;

-- Роли пользователей
CREATE TABLE roles (
    role_id   SERIAL PRIMARY KEY,
    role_name VARCHAR(50) NOT NULL UNIQUE
);

-- Пользователи системы (вход только по логину)
CREATE TABLE users (
    user_id     SERIAL PRIMARY KEY,
    last_name   VARCHAR(50) NOT NULL,
    first_name  VARCHAR(50) NOT NULL,
    middle_name VARCHAR(50),
    login       VARCHAR(50) NOT NULL UNIQUE,
    role_id     INTEGER NOT NULL REFERENCES roles(role_id) ON UPDATE CASCADE ON DELETE RESTRICT
);

-- Справочники товара
CREATE TABLE categories (
    category_id   SERIAL PRIMARY KEY,
    category_name VARCHAR(50) NOT NULL UNIQUE
);
CREATE TABLE subcategories (
    subcategory_id   SERIAL PRIMARY KEY,
    subcategory_name VARCHAR(50) NOT NULL UNIQUE
);
CREATE TABLE manufacturers (
    manufacturer_id   SERIAL PRIMARY KEY,
    manufacturer_name VARCHAR(100) NOT NULL UNIQUE
);

-- Модели обуви (image_path - имя файла в папке resources/images приложения)
CREATE TABLE products (
    product_id      SERIAL PRIMARY KEY,
    category_id     INTEGER NOT NULL REFERENCES categories(category_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    subcategory_id  INTEGER NOT NULL REFERENCES subcategories(subcategory_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    manufacturer_id INTEGER NOT NULL REFERENCES manufacturers(manufacturer_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    product_name    VARCHAR(200) NOT NULL,
    image_path      VARCHAR(255),
    description     TEXT,
    composition     TEXT,
    price           NUMERIC(10,2) NOT NULL CHECK (price >= 0),
    UNIQUE (product_name, manufacturer_id)
);

-- Размеры обуви (бывают дробные: 36.5)
CREATE TABLE sizes (
    size_id    SERIAL PRIMARY KEY,
    size_value NUMERIC(3,1) NOT NULL UNIQUE
);

-- Товарные позиции: модель + размер + доступное количество
CREATE TABLE stock_items (
    stock_item_id      SERIAL PRIMARY KEY,
    product_id         INTEGER NOT NULL REFERENCES products(product_id) ON UPDATE CASCADE ON DELETE CASCADE,
    size_id            INTEGER NOT NULL REFERENCES sizes(size_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    quantity_available INTEGER NOT NULL DEFAULT 0 CHECK (quantity_available >= 0),
    UNIQUE (product_id, size_id)
);

-- Заказы
CREATE TABLE orders (
    order_id   SERIAL PRIMARY KEY,
    order_date DATE NOT NULL DEFAULT CURRENT_DATE,
    user_id    INTEGER NOT NULL REFERENCES users(user_id) ON UPDATE CASCADE ON DELETE RESTRICT
);

-- Состав заказа (unit_price - цена за единицу на момент оформления)
CREATE TABLE order_items (
    order_item_id SERIAL PRIMARY KEY,
    order_id      INTEGER NOT NULL REFERENCES orders(order_id) ON UPDATE CASCADE ON DELETE CASCADE,
    product_id    INTEGER NOT NULL REFERENCES products(product_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    size_id       INTEGER NOT NULL REFERENCES sizes(size_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    quantity      INTEGER NOT NULL CHECK (quantity > 0),
    unit_price    NUMERIC(10,2) NOT NULL CHECK (unit_price >= 0)
);

CREATE INDEX idx_products_category ON products(category_id);
CREATE INDEX idx_order_items_order ON order_items(order_id);
CREATE INDEX idx_orders_date ON orders(order_date);

